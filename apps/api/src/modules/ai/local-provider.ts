  private classifyDocument(name: string, text: string): string {
    const lower = (name + " " + text.slice(0, 1000)).toLowerCase();
    if (/contrato|contract/.test(lower)) return "Contrato";
    if (/fatura|invoice|factura/.test(lower)) return "Fatura";
    if (/relatório|report|relatorio/.test(lower)) return "Relatório";
    if (/proposta|proposal|quote/.test(lower)) return "Proposta";
    if (/orçamento|orcamento|budget/.test(lower)) return "Orçamento";
    if (/política|politica|policy/.test(lower)) return "Política";
    if (/manual|guia|guide/.test(lower)) return "Manual";
    if (/apresentação|presentation|slides/.test(lower)) return "Apresentação";
    if (/email|carta|letter/.test(lower)) return "Correspondência";
    return "Documento Geral";
  }

  private detectContentType(text: string): string {
    if (/^\s*%PDF/.test(text)) return "PDF (binário)";
    if (/^\s*<\?xml/.test(text)) return "XML";
    if (/^\s*<html/.test(text)) return "HTML";
    if (/^\s*\{[\s\S]*\}\s*$/.test(text)) return "JSON";
    return "Texto";
  }

  private extractKeywords(text: string): string[] {
    const stopWords = new Set(["o", "a", "os", "as", "de", "do", "da", "dos", "das", "e", "ou", "em", "no", "na", "nos", "nas", "por", "para", "com", "sem", "que", "um", "uma", "the", "a", "an", "and", "or", "in", "on", "at", "to", "for", "of", "with", "by", "is", "are", "was", "were", "this", "that"]);
    const words = text.toLowerCase().split(/[\s,;:.!?()\-/\\]+/).filter((w) => w.length > 3 && !stopWords.has(w) && !/^\d+$/.test(w));
    const freq = new Map<string, number>();
    for (const w of words) freq.set(w, (freq.get(w) ?? 0) + 1);
    return [...freq.entries()].sort((a, b) => b[1] - a[1]).slice(0, 10).map(([w]) => w);
  }

  private guessFieldType(name: string): string {
    const lower = name.toLowerCase().trim();
    if (FIELD_TYPE_MAP[lower]) return FIELD_TYPE_MAP[lower];
    for (const [key, type] of Object.entries(FIELD_TYPE_MAP)) {
      if (lower.includes(key)) return type;
    }
    return "text";
  }

  private slugify(s: string): string {
    return s.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 80) || "campo";
  }

  private capitalize(s: string): string {
    return s.charAt(0).toUpperCase() + s.slice(1);
  }

  private result(content: string, actionType: string | undefined, actionData: unknown | undefined, tokensInput: number, output: string): AIProviderResult {
    return {
      content,
      actionType,
      actionData,
      tokensInput,
      tokensOutput: Math.ceil(output.length / 4),
      costUsd: 0 // Local provider is free
    };
  }

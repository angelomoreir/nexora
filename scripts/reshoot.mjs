import puppeteer from "puppeteer-core";
const WEB = "http://localhost:5173", PW = "XPTOdemo2024!";
const browser = await puppeteer.launch({ executablePath: "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe", headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1.5 });
await page.goto(`${WEB}/login`, { waitUntil: "networkidle0" });
await page.evaluate(() => localStorage.setItem("i18nextLng", "pt-PT"));
await page.type('input[type="email"]', "ana@xpto.pt");
await page.type('input[type="password"]', PW);
await Promise.all([page.waitForNavigation({ waitUntil: "networkidle0", timeout: 30000 }).catch(() => {}), page.click('button[type="submit"]')]);
await new Promise(r => setTimeout(r, 1500));
await page.goto(`${WEB}${process.argv[2] || "/admin/users"}`, { waitUntil: "networkidle0" });
await new Promise(r => setTimeout(r, 1200));
await page.screenshot({ path: `docs/manual/shots/${process.argv[3] || "21-admin-users"}.png` });
console.log("reshot", process.argv[3] || "21-admin-users");
await browser.close();
